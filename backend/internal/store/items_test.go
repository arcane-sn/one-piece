package store

import "testing"

func TestItemsCRUDDoesNotTouchContentVersion(t *testing.T) {
	s, c := newCard(t)
	it, err := s.CreateItem(c.ID, "agent", "Add login route", "Body")
	if err != nil || it.Kind != "agent" || it.Title != "Add login route" {
		t.Fatalf("create = %+v, %v", it, err)
	}
	s.CreateItem(c.ID, "qa", "Wrong password", "")
	it, err = s.UpdateItem(it.ID, "Add login endpoint", "New body")
	if err != nil || it.Title != "Add login endpoint" || it.Kind != "agent" {
		t.Fatalf("update = %+v, %v", it, err)
	}
	if got, _ := s.GetCard(c.ID); got.ContentVersion != 1 {
		t.Fatalf("items must not bump the content version, got %d", got.ContentVersion)
	}
	items, _ := s.ListItems(c.ID)
	if len(items) != 2 || items[0].Kind != "agent" || items[1].Kind != "qa" {
		t.Fatalf("list = %+v", items)
	}
	if err := s.DeleteItem(it.ID); err != nil {
		t.Fatal(err)
	}
	if items, _ = s.ListItems(c.ID); len(items) != 1 {
		t.Fatalf("after delete: %+v", items)
	}
}

func TestReplaceItemsAndValidation(t *testing.T) {
	s, c := newCard(t)
	s.CreateItem(c.ID, "agent", "old", "")
	out, err := s.ReplaceItems(c.ID, []Item{{Kind: "agent", Title: "A1"}, {Kind: "agent", Title: "A2"}, {Kind: "qa", Title: "Q1"}})
	if err != nil || len(out) != 3 || out[1].Title != "A2" || out[1].Position != 1 {
		t.Fatalf("replace = %+v, %v", out, err)
	}
	if items, _ := s.ListItems(c.ID); len(items) != 3 {
		t.Fatalf("old items should be gone: %+v", items)
	}
	if _, err := s.ReplaceItems(c.ID, []Item{{Kind: "bogus", Title: "x"}}); err == nil {
		t.Fatal("bad kind should fail")
	}
	if items, _ := s.ListItems(c.ID); len(items) != 3 {
		t.Fatal("failed replace must keep the old items")
	}
	if _, err := s.CreateItem(c.ID, "qa", " ", ""); err == nil {
		t.Fatal("empty title should fail")
	}
	if _, err := s.CreateItem(9999, "qa", "x", ""); err != ErrNotFound {
		t.Fatalf("missing card: %v", err)
	}
	if _, err := s.UpdateItem(9999, "x", ""); err != ErrNotFound {
		t.Fatalf("missing item: %v", err)
	}
}

func TestItemStatusLogAndTechnicalFlows(t *testing.T) {
	s, c := newCard(t)
	out, err := s.ReplaceItems(c.ID, []Item{{Kind: "agent", Title: "A1", Log: []string{"Generated by Claude"}}})
	if err != nil {
		t.Fatal(err)
	}
	it := out[0]
	if it.Status != "todo" || len(it.Log) != 1 {
		t.Fatalf("new item = %+v", it)
	}
	if it, err = s.SetItemStatus(it.ID, "done"); err != nil || it.Status != "done" {
		t.Fatalf("status = %+v, %v", it, err)
	}
	if _, err = s.SetItemStatus(it.ID, "bogus"); err == nil {
		t.Fatal("bad status should fail")
	}
	s.AppendItemLog(it.ID, "Edited by you")
	got, _ := s.GetItem(it.ID)
	if got.Status != "done" || len(got.Log) != 2 || got.Log[1] != "Edited by you" {
		t.Fatalf("after log = %+v", got)
	}

	f, err := s.CreateItemFlow(it.ID, "Verify password", "App -> DB: lookup")
	if err != nil || f.ItemID != it.ID {
		t.Fatalf("item flow = %+v, %v", f, err)
	}
	if biz, _ := s.ListFlows(c.ID); len(biz) != 0 {
		t.Fatalf("technical flows must not show as business flows: %+v", biz)
	}
	if tech, _ := s.ListItemFlows(it.ID); len(tech) != 1 {
		t.Fatalf("technical flows = %+v", tech)
	}
	s.UpdateFlow(f.ID, "Verify", "A -> B")
	s.DeleteFlow(f.ID)
	if card, _ := s.GetCard(c.ID); card.ContentVersion != 1 {
		t.Fatalf("technical flows must not bump the ticket version, got %d", card.ContentVersion)
	}
	f2, _ := s.CreateItemFlow(it.ID, "keep?", "")
	s.DeleteItem(it.ID)
	if _, err := s.GetFlow(f2.ID); err != ErrNotFound {
		t.Fatalf("deleting an item should delete its technical flows: %v", err)
	}
}
